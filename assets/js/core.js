export function getCompositePolicy() {
  const cp = State.schema && State.schema.composite;
  return {
    coverageShrinkageExponent: (cp && Number.isFinite(cp.coverageShrinkageExponent)) ? cp.coverageShrinkageExponent : 2,
    imputationEnabled: !!(cp && cp.imputation && cp.imputation.enabled),
    minPeerCount: (cp && cp.imputation && Number.isFinite(cp.imputation.minPeerCount)) ? cp.imputation.minPeerCount : 3,
    maxImputedWeightShare: (cp && cp.imputation && Number.isFinite(cp.imputation.maxImputedWeightShare)) ? cp.imputation.maxImputedWeightShare : 0.30,
    imputedConfidenceFactor: (cp && cp.imputation && Number.isFinite(cp.imputation.imputedConfidenceFactor)) ? cp.imputation.imputedConfidenceFactor : 0.5,
    minCoverageDisplay: (cp && Number.isFinite(cp.minCoverageDisplay)) ? cp.minCoverageDisplay : 0.30,
    // Empirical-Bayes shrinkage for the leaderboard point score (replaces the
    // blunt raw×√coverage penalty in compositeScoreImputed/compositeUncertainty).
    // A model's score is its own observed-cell mean shrunk toward a conservative
    // global-median baseline by `priorWeight` pseudo-weight, then docked a
    // nonlinear penalty only once confidence drops below `confThreshold`. Net:
    // missing benches are neither zeroed (penalty) nor scored as full marks —
    // they pull toward "average until proven otherwise", with the pull inversely
    // proportional to how much real data the model has. enabled:false → callers
    // fall back to raw×√coverage.
    eb: (() => {
      const e = (cp && cp.eb) || {};
      return {
        enabled: e.enabled !== false,
        priorWeight: Number.isFinite(e.priorWeight) ? e.priorWeight : 30,
        confThreshold: (Number.isFinite(e.confThreshold) && e.confThreshold > 0) ? e.confThreshold : 0.65,
        sigmaPenaltyMax: Number.isFinite(e.sigmaPenaltyMax) ? e.sigmaPenaltyMax : 18,
      };
    })(),
    // Leaderboard rank gate (2026-06-07): models missing a required bench for the
    // active preset (or below coverageFloor of preset weight) are demoted out of
    // the main ranking into a "Limited Coverage" band. enabled:false → no gate.
    rankGate: (() => {
      const r = (cp && cp.rankGate) || {};
      return {
        enabled: r.enabled !== false,
        demoteMissingRequired: r.demoteMissingRequired !== false,
        coverageFloor: (Number.isFinite(r.coverageFloor) && r.coverageFloor >= 0) ? r.coverageFloor : 0.4,
      };
    })(),
    uncertainty: (() => {
      const u = (cp && cp.uncertainty) || {};
      return {
        enabled: u.enabled !== false,
        sigmaMax: Number.isFinite(u.sigmaMax) ? u.sigmaMax : 14,
        contraDivisor: (Number.isFinite(u.contraDivisor) && u.contraDivisor > 0) ? u.contraDivisor : 2,
        imputeSigma: Number.isFinite(u.imputeSigma) ? u.imputeSigma : 12,
        sparsityAlpha: Number.isFinite(u.sparsityAlpha) ? u.sparsityAlpha : 0.25,
        bandMult: (Number.isFinite(u.bandMult) && u.bandMult > 0) ? u.bandMult : 1,
        minSourcesForCI: Number.isFinite(u.minSourcesForCI) ? u.minSourcesForCI : 2,
      };
    })(),
  };
}

