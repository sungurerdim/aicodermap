export function getCompositePolicy() {
  const cp = State.schema && State.schema.composite;
  return {
    coverageShrinkageExponent: (cp && Number.isFinite(cp.coverageShrinkageExponent)) ? cp.coverageShrinkageExponent : 2,
    imputationEnabled: !!(cp && cp.imputation && cp.imputation.enabled),
    minPeerCount: (cp && cp.imputation && Number.isFinite(cp.imputation.minPeerCount)) ? cp.imputation.minPeerCount : 3,
    maxImputedWeightShare: (cp && cp.imputation && Number.isFinite(cp.imputation.maxImputedWeightShare)) ? cp.imputation.maxImputedWeightShare : 0.30,
    imputedConfidenceFactor: (cp && cp.imputation && Number.isFinite(cp.imputation.imputedConfidenceFactor)) ? cp.imputation.imputedConfidenceFactor : 0.5,
    minCoverageDisplay: (cp && Number.isFinite(cp.minCoverageDisplay)) ? cp.minCoverageDisplay : 0.30,
    // Empirical-Bayes shrinkage for the leaderboard point score (replaces the
    // blunt raw×√coverage penalty in compositeScoreImputed/compositeUncertainty).
    // A model's score is its own observed-cell mean shrunk toward a conservative
    // global-median baseline by `priorWeight` pseudo-weight, then docked a
    // nonlinear penalty only once confidence drops below `confThreshold`. Net:
    // missing benches are neither zeroed (penalty) nor scored as full marks —
    // they pull toward "average until proven otherwise", with the pull inversely
    // proportional to how much real data the model has. enabled:false → callers
    // fall back to raw×√coverage.
    eb: (() => {
      const e = (cp && cp.eb) || {};
      return {
        enabled: e.enabled !== false,
        priorWeight: Number.isFinite(e.priorWeight) ? e.priorWeight : 30,
        confThreshold: (Number.isFinite(e.confThreshold) && e.confThreshold > 0) ? e.confThreshold : 0.65,
        sigmaPenaltyMax: Number.isFinite(e.sigmaPenaltyMax) ? e.sigmaPenaltyMax : 18,
      };
    })(),
    // Leaderboard rank gate (2026-06-07, coverage-aware missing-required
    // 2026-07-16): models below coverageFloor overall, OR missing a required
    // bench for the active preset WHILE ALSO below missingRequiredCoverageFloor,
    // are demoted out of the main ranking into a "Limited Coverage" band. A
    // well-covered model missing just one required bench (e.g. a vendor that
    // genuinely never published it) stays ranked on its EB-shrunk score instead.
    // enabled:false → no gate.
    rankGate: (() => {
      const r = (cp && cp.rankGate) || {};
      return {
        enabled: r.enabled !== false,
        demoteMissingRequired: r.demoteMissingRequired !== false,
        coverageFloor: (Number.isFinite(r.coverageFloor) && r.coverageFloor >= 0) ? r.coverageFloor : 0.4,
        missingRequiredCoverageFloor: (Number.isFinite(r.missingRequiredCoverageFloor) && r.missingRequiredCoverageFloor >= 0) ? r.missingRequiredCoverageFloor : 0.5,
      };
    })(),
    uncertainty: (() => {
      const u = (cp && cp.uncertainty) || {};
      return {
        enabled: u.enabled !== false,
        sigmaMax: Number.isFinite(u.sigmaMax) ? u.sigmaMax : 14,
        contraDivisor: (Number.isFinite(u.contraDivisor) && u.contraDivisor > 0) ? u.contraDivisor : 2,
        imputeSigma: Number.isFinite(u.imputeSigma) ? u.imputeSigma : 12,
        sparsityAlpha: Number.isFinite(u.sparsityAlpha) ? u.sparsityAlpha : 0.25,
        bandMult: (Number.isFinite(u.bandMult) && u.bandMult > 0) ? u.bandMult : 1,
        minSourcesForCI: Number.isFinite(u.minSourcesForCI) ? u.minSourcesForCI : 2,
      };
    })(),
  };
}

// Release-recency policy (2026-07-24). The product promise is speed of news —
// a model released today must be findable today. Two knobs, schema-overridable:
//   newWindowDays     how long a model counts as a NEW RELEASE (badge + strip)
//   graceMinCoverage  the coverage a new model needs to skip the rank gate
// Rationale: the gate's requiredBenches (swePro, sweMulti, cfElo…) come from
// independent leaderboards that run WEEKS after a launch, so every brand-new
// model was structurally demoted into the Limited-Coverage band during exactly
// the window where its news value is highest (claude-opus-5 at 39% coverage,
// 2026-07-24). The grace floor keeps zero-evidence stubs out — a new model
// still needs real cells to rank, it just no longer needs the ones nobody has
// published yet.
export function getRecencyPolicy() {
  const rp = (State.schema && State.schema.recency) || {};
  return {
    newWindowDays: (Number.isFinite(rp.newWindowDays) && rp.newWindowDays > 0) ? rp.newWindowDays : 3,
    graceMinCoverage: (Number.isFinite(rp.graceMinCoverage) && rp.graceMinCoverage >= 0) ? rp.graceMinCoverage : 0.25,
  };
}

// Whole days since `model.released`, or null when the date is missing/invalid.
// Negative (future-dated) values clamp to 0 so a timezone skew on launch day
// still reads as "released today".
export function daysSinceRelease(model, now) {
  const iso = model && model.released;
  if (!iso) return null;
  const ts = Date.parse(String(iso).length <= 10 ? `${iso}T00:00:00Z` : iso);
  if (!Number.isFinite(ts)) return null;
  const ref = now instanceof Date ? now.getTime() : (Number.isFinite(now) ? now : Date.now());
  return Math.max(0, Math.floor((ref - ts) / 86400000));
}

export function isRecentRelease(model, now) {
  const days = daysSinceRelease(model, now);
  return days != null && days <= getRecencyPolicy().newWindowDays;
}

