// Source-provenance helpers. Builds the compact in-card "Sources (N unique)"
// footer and the per-cell Markdown export used by the doc-icon action.

import { State, BENCH_KEYS } from './core.js';
import { contradictionFor, fmtScore } from './data.js';
import { t } from './i18n.js';

// Aggregate every source mention across all bench entries for a model and
// dedupe by URL (falling back to source name). Returns counts grouped by
// tier so the UI can colour rows and the user can see at a glance whether
// the data leans on independent verification or vendor self-reports.
export function modelSourcesSummary(model) {
  const seen = new Map();
  let totalDatapoints = 0;
  for (const k of BENCH_KEYS) {
    const entries = State.sources[`${model.id}.${k}`];
    if (!Array.isArray(entries)) continue;
    for (const e of entries) {
      if (!e || typeof e !== 'object') continue;
      totalDatapoints++;
      const dedupeKey = e.url || e.source || '?';
      if (!seen.has(dedupeKey)) {
        seen.set(dedupeKey, {
          tier: e.tier || '?',
          source: e.source || '?',
          url: e.url || null,
          count: 1,
        });
      } else {
        seen.get(dedupeKey).count++;
      }
    }
  }
  const byTier = { I: [], S: [], C: [], '?': [] };
  for (const v of seen.values()) {
    const bucket = byTier[v.tier] ? v.tier : '?';
    byTier[bucket].push(v);
  }
  // Stable order inside each tier: most-cited first, then alphabetical.
  for (const tier of Object.keys(byTier)) {
    byTier[tier].sort((a, b) => b.count - a.count || a.source.localeCompare(b.source));
  }
  return { byTier, totalUnique: seen.size, totalDatapoints };
}

// Per-bench provenance breakdown rendered as Markdown so users can paste
// citations into reports / issues / docs. One file per model, one section
// per benchmark, every source row carries tier + trustScore + value + date.
export function buildSourcesMarkdown(model) {
  const lines = [];
  const today = new Date().toISOString().slice(0, 10);
  lines.push(`# ${model.name} — source provenance`);
  lines.push('');
  lines.push(`Generated by AICoderMap on ${today}. Last data refresh: ${model.lastUpdated || '—'}.`);
  lines.push('');
  lines.push(`Live page: https://sungurerdim.github.io/aicodermap/`);
  lines.push('');
  lines.push('## Per-benchmark sources');
  lines.push('');

  let any = false;
  for (const k of BENCH_KEYS) {
    const entries = State.sources[`${model.id}.${k}`];
    if (!Array.isArray(entries) || entries.length === 0) continue;
    any = true;

    const benchLabel = t(`benchmarks.${k}.name`) || k;
    const score = model.bench?.[k];
    const scoreStr = score != null && Number.isFinite(score) ? fmtScore(score) : '—';

    const c = contradictionFor(model.id, k);
    const flag = c ? (c.severity === 'danger' ? ' 🚨' : ' ⚠') : '';
    const deltaStr = c ? ` — Δ=${c.delta.toFixed(1)}pp` : '';

    lines.push(`### ${benchLabel} (\`${k}\`): ${scoreStr}${flag}${deltaStr}`);
    lines.push('');
    for (const e of entries) {
      const tier = e.tier || '?';
      const trust = (e.trustScore != null && Number.isFinite(e.trustScore))
        ? e.trustScore.toFixed(2) : '?';
      const value = e.value != null ? e.value : '—';
      const date = e.date || '—';
      const src = e.source || '?';
      const urlPart = e.url ? ` <${e.url}>` : '';
      lines.push(`- **${tier}-tier** [trust ${trust}] ${src}${urlPart} — value ${value} — ${date}`);
    }
    lines.push('');
  }
  if (!any) {
    lines.push('_No source records on file for this model._');
    lines.push('');
  }
  lines.push('---');
  lines.push('Tier legend: **I** = independent benchmark / leaderboard, **S** = vendor self-report, **C** = community / aggregator. The skill\'s autoResolveWinner picks the highest-trust source when sources disagree; cells with same-tier disagreement carry a confidence haircut in the composite.');
  lines.push('');
  return lines.join('\n');
}

export function exportSourcesMarkdown(model) {
  const md = buildSourcesMarkdown(model);
  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `aicodermap-${model.id}-sources.md`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
