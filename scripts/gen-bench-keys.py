#!/usr/bin/env python3
"""SSOT bench-key sync (F0.1).

Single source of truth for bench keys:
  data/sources-whitelist.json _schema.benchCategories
→ assets/js/core.js BENCH_KEYS array (between AUTO-GENERATED markers)

Usage:
  python scripts/gen-bench-keys.py          # overwrite BENCH_KEYS if out of sync
  python scripts/gen-bench-keys.py --check  # exit 1 if core.js is out of sync (for pre-commit/CI)
  python scripts/gen-bench-keys.py --check-regex-drift  # 4.1: exit 1 if the
        # bench_score_labeled regex references a bench name no longer grounded in
        # _schema.benchAliases (a rename/removal the regex didn't follow).

The script is idempotent: re-running when already in sync writes nothing.
Stdlib-only.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT / "scripts"))
from lib.util import slug_norm as _norm  # noqa: E402  (SSOT)

WHITELIST = PROJECT / "data" / "sources-whitelist.json"
CORE_JS = PROJECT / "assets" / "js" / "core.js"

_MARKER_START = "// AUTO-GENERATED by scripts/gen-bench-keys.py"
_MARKER_END = "// END-AUTO-GENERATED BENCH_KEYS"

# Row width target when rendering the JS array (characters, not key count)
_ROW_WIDTH = 72


def load_keys_from_whitelist() -> list[str]:
    """Return ordered deduplicated bench keys from _schema.benchCategories."""
    wl = json.loads(WHITELIST.read_text(encoding="utf-8"))
    categories = wl.get("_schema", {}).get("benchCategories", [])
    seen: set[str] = set()
    keys: list[str] = []
    for cat in categories:
        for k in cat.get("keys", []):
            if isinstance(k, str) and k and k not in seen:
                seen.add(k)
                keys.append(k)
    return keys


def _render_js_block(keys: list[str]) -> str:
    """Render the JS BENCH_KEYS array between markers."""
    rows: list[str] = []
    row: list[str] = []
    row_width = 2  # leading "  "
    for k in keys:
        entry = f"'{k}'"
        token_width = len(entry) + 2  # ", " separator
        if row and row_width + token_width > _ROW_WIDTH:
            rows.append("  " + ", ".join(row) + ",")
            row = []
            row_width = 2
        row.append(entry)
        row_width += token_width
    if row:
        rows.append("  " + ", ".join(row) + ",")

    body = "\n".join(rows)
    return (
        f"{_MARKER_START}"
        f" — source: data/sources-whitelist.json _schema.benchCategories\n"
        f"export const BENCH_KEYS = [\n"
        f"{body}\n"
        f"];\n"
        f"{_MARKER_END}"
    )


def _extract_current_keys(text: str) -> list[str]:
    """Extract keys currently in BENCH_KEYS array (ignores ordering)."""
    m = re.search(r"export const BENCH_KEYS\s*=\s*\[([^\]]+)\]", text, re.DOTALL)
    if not m:
        return []
    return re.findall(r"'([^']+)'", m.group(1))


def _replace_bench_keys_block(text: str, new_block: str) -> str:
    """Replace BENCH_KEYS declaration in core.js text with new_block."""
    if _MARKER_START in text:
        # Markers already present — replace between them
        pattern = re.escape(_MARKER_START) + r".*?" + re.escape(_MARKER_END)
        return re.sub(pattern, new_block, text, flags=re.DOTALL)
    # First run — replace bare export const BENCH_KEYS = [...]; declaration
    pattern = r"export const BENCH_KEYS\s*=\s*\[[^\]]*\];"
    return re.sub(pattern, new_block, text, flags=re.DOTALL)


def _extract_bench_group(regex: str) -> str | None:
    """Return the inner content of the `(?<bench>...)` named group via balanced
    unescaped-paren counting."""
    anchor = "(?<bench>"
    start = regex.find(anchor)
    if start < 0:
        return None
    i = start + len(anchor)
    depth = 1
    while i < len(regex) and depth > 0:
        c = regex[i]
        if c == "(" and regex[i - 1] != "\\":
            depth += 1
        elif c == ")" and regex[i - 1] != "\\":
            depth -= 1
        i += 1
    return regex[start + len(anchor) : i - 1]


def _split_top_alternation(s: str) -> list[str]:
    """Split on top-level `|`, ignoring `|` inside (?:...) groups and [...] classes."""
    out: list[str] = []
    depth = 0
    cur = ""
    i = 0
    while i < len(s):
        c = s[i]
        if c == "[":
            j = s.find("]", i)
            if j < 0:
                j = len(s) - 1
            cur += s[i : j + 1]
            i = j + 1
            continue
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        if c == "|" and depth == 0:
            out.append(cur)
            cur = ""
            i += 1
            continue
        cur += c
        i += 1
    if cur:
        out.append(cur)
    return out


def _flatten_alt(a: str) -> str:
    """Reduce one regex alternative to a representative literal name."""
    a = re.sub(r"\(\?:([^)|]*)(?:\|[^)]*)?\)\??", r"\1", a)  # (?:Pro|Verified) -> Pro
    a = re.sub(r"\[[^\]]*\]\??", "", a)  # char classes (separators) -> ''
    a = re.sub(r"\\s[*+?]?", "", a)  # \s, \s*, \s+ -> ''
    a = re.sub(r"\\d\{[^}]*\}", "", a)  # \d{2,4} -> ''
    a = a.replace("v?", "").replace("?", "")
    a = re.sub(r"[\\(){}:*+]", "", a)
    return a


def check_regex_drift() -> int:
    """4.1 — fail (exit 1) when a bench name hardcoded in bench_score_labeled is
    no longer grounded in _schema.benchAliases (the SSOT alias map)."""
    wl = json.loads(WHITELIST.read_text(encoding="utf-8"))
    schema = wl.get("_schema", {})
    pat = ((schema.get("regexLibrary") or {}).get("patterns") or {}).get(
        "bench_score_labeled"
    )
    aliases = {
        k: v
        for k, v in (schema.get("benchAliases") or {}).items()
        if not k.startswith("_")
    }
    if not pat or not aliases:
        print(
            "DRIFT-CHECK: bench_score_labeled or benchAliases missing", file=sys.stderr
        )
        return 1
    grp = _extract_bench_group(pat.get("regex", ""))
    if not grp:
        print("DRIFT-CHECK: could not extract (?<bench>) group", file=sys.stderr)
        return 1

    grounded_names = {_norm(x) for k, v in aliases.items() for x in ([k] + list(v))}
    grounded_names.discard("")
    stale: list[str] = []
    for alt in _split_top_alternation(grp):
        sample = _norm(_flatten_alt(alt))
        if not sample:
            continue
        if not any(sample == g or sample in g or g in sample for g in grounded_names):
            stale.append(alt.strip())

    if stale:
        print(
            "DRIFT: bench_score_labeled references name(s) not grounded in "
            "_schema.benchAliases (rename/removal the regex did not follow):",
            file=sys.stderr,
        )
        for s in stale:
            print(f"  - {s}", file=sys.stderr)
        print(
            "Fix: update the regex alternation OR restore the alias in benchAliases.",
            file=sys.stderr,
        )
        return 1
    print(
        f"OK: bench_score_labeled alternation grounded in benchAliases "
        f"({len(_split_top_alternation(grp))} alternatives checked)"
    )
    return 0


def main() -> int:
    if "--check-regex-drift" in sys.argv:
        return check_regex_drift()
    check_only = "--check" in sys.argv

    keys = load_keys_from_whitelist()
    if not keys:
        print(
            "ERROR: no bench keys found in whitelist _schema.benchCategories",
            file=sys.stderr,
        )
        return 1

    text = CORE_JS.read_text(encoding="utf-8")
    current = set(_extract_current_keys(text))
    canonical = set(keys)

    if current == canonical:
        if not check_only:
            # Ensure markers are present even when content matches
            if _MARKER_START not in text:
                new_text = _replace_bench_keys_block(text, _render_js_block(keys))
                CORE_JS.write_text(new_text, encoding="utf-8")
                print(
                    f"Added AUTO-GENERATED markers ({len(keys)} keys, content unchanged)"
                )
            else:
                print(f"OK: BENCH_KEYS already in sync ({len(keys)} keys)")
        else:
            print(f"OK: BENCH_KEYS in sync ({len(keys)} keys)")
        return 0

    added = sorted(canonical - current)
    removed = sorted(current - canonical)

    if check_only:
        if added:
            print(f"DRIFT: missing from core.js BENCH_KEYS: {added}", file=sys.stderr)
        if removed:
            print(
                f"DRIFT: extra in core.js BENCH_KEYS (not in whitelist): {removed}",
                file=sys.stderr,
            )
        return 1

    new_block = _render_js_block(keys)
    new_text = _replace_bench_keys_block(text, new_block)
    CORE_JS.write_text(new_text, encoding="utf-8")
    if added:
        print(f"Added to BENCH_KEYS: {added}")
    if removed:
        print(f"Removed from BENCH_KEYS: {removed}")
    print(f"Updated core.js BENCH_KEYS: {len(current)} → {len(keys)} keys")
    return 0


if __name__ == "__main__":
    sys.exit(main())
